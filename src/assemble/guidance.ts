/**
 * H-2: 根据压力等级动态生成知识库参考引导语。
 * low tier → 详细引导（分层使用说明 + 冲突处理策略）
 * medium tier → 精简引导（优先级提示）
 * high tier → 极简引导（仅核心提示）
 *
 * 从 index.ts 模块级提取到独立模块，通过依赖注入传递 logger 等。
 */
export function buildKnowledgeGuidance(tier: string, hasSections: boolean): string {
  if (!hasSections) return '';
  const header = '\n# 知识库参考\n';
  switch (tier) {
    case 'low':
      return header + [
        '以下为知识库检索结果，按来源分为三层。请注意：这些内容来自历史对话，',
        '可能【不适用于当前问题】。你必须以用户当前问题为核心，仅引用与当前',
        '问题【直接相关】的内容，忽略所有无关信息。',
        '',
        '1. 经验总结（历史参考）：历史对话中的经验，可能存在主题偏差',
        '2. 知识图谱（结构参考）：代码实体关系，用于理解项目结构',
        '3. 记忆文件（内容参考）：代码片段和文档，用于补充细节',
        '',
        '使用原则（重要）：',
        '- 始终以用户当前问题为最高优先级，不要被历史内容主导任务方向',
        '- 如果检索结果与当前问题无关或主题不同，必须忽略，基于你的知识回答',
        '- 只有在检索结果【明确与当前问题相关】时，才将其作为参考',
        '- 经验中的"不推荐"做法仅适用于经验所描述的场景，不适用于当前问题',
        '- 不要因为检索结果提到了某个项目或工具，就转而讨论那个项目或工具',
      ].join('\n');
    case 'medium':
      return header + [
        '以下为知识库检索结果，仅供参考。',
        '请专注于用户当前问题，忽略与当前问题无关的内容。',
      ].join('\n');
    case 'high':
      return header + '请专注于用户当前问题，忽略以下所有检索内容。如有需要，请自行搜索。';
    default:
      return header + '以下为知识库检索结果，仅供参考。请始终专注于用户当前问题。';
  }
}